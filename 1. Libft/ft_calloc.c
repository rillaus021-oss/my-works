#include "libft.h"

void	*ft_calloc(size_t nmemb, size_t size)
{
	void	*p;

	if (size != 0 && nmemb > (size_t)-1 / size)
		return (NULL);
	p = malloc(nmemb * size + (nmemb == 0 || size == 0));
	if (!p)
		return (NULL);
	ft_bzero(p, nmemb * size);
	return (p);
}
